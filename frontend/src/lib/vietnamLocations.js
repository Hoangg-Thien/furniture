// Hàm lấy danh sách tên các Tỉnh / Thành phố
export function getAllProvinces() {
  const names = VIETNAM_LOCATIONS.map((loc) => loc.name)
  return Array.from(new Set(names))
}

// Hàm lấy danh sách Quận / Huyện theo Tỉnh / Thành phố
export function getDistricts(provinceName) {
  if (!provinceName) return []
  const found = VIETNAM_LOCATIONS.find(
    (loc) => loc.name.toLowerCase() === provinceName.trim().toLowerCase()
  )
  if (!found || !Array.isArray(found.districts) || found.districts.length === 0) {
    // Trả về danh sách mặc định nếu chưa có chi tiết
    return ['Quận Trung tâm', 'Huyện Ngoại thành', 'Khu vực khác']
  }
  return found.districts.map((d) => d.name)
}

// Hàm lấy danh sách Phường / Xã theo Tỉnh và Quận/Huyện
export function getWards(provinceName, districtName) {
  if (!provinceName || !districtName) return []
  const foundProv = VIETNAM_LOCATIONS.find(
    (loc) => loc.name.toLowerCase() === provinceName.trim().toLowerCase()
  )
  if (!foundProv || !Array.isArray(foundProv.districts)) return []
  const foundDist = foundProv.districts.find(
    (d) => d.name.toLowerCase() === districtName.trim().toLowerCase()
  )
  if (!foundDist || !Array.isArray(foundDist.wards) || foundDist.wards.length === 0) {
    return ['Phường Trung tâm', 'Phường 1', 'Phường 2', 'Xã Trung tâm', 'Khu vực khác']
  }
  return foundDist.wards
}

