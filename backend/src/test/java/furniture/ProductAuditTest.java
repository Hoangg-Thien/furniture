package furniture;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.mock;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.ClassPathResource;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import org.springframework.transaction.support.TransactionTemplate;
import com.fasterxml.jackson.databind.ObjectMapper;
import furniture.model.admin.product.SaveProductRequest;
import furniture.repository.AdminCategoryRepository;
import furniture.repository.AdminProductRepository;
import furniture.repository.ProductAuditRepository;
import furniture.service.AdminProductService;
import furniture.service.FileStorageService;

class ProductAuditTest {
    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private ProductAuditRepository audit;
    private AdminProductService products;
    private TransactionTemplate transaction;

    @BeforeEach
    void setup() throws Exception {
        database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .setName("audit_" + java.util.UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE").build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, username VARCHAR(50))");
        jdbc.execute("INSERT INTO users VALUES (1, 'admin'), (2, 'content')");
        jdbc.execute("CREATE TABLE categories (id BIGINT PRIMARY KEY, name VARCHAR(150))");
        jdbc.execute("INSERT INTO categories VALUES (1, 'Chairs')");
        jdbc.execute("""
                CREATE TABLE products (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(200), description TEXT, category_id BIGINT, unit VARCHAR(50), selling_price NUMERIC(15,2),
                quantity INT, is_active BOOLEAN, image_url TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)
                """);
        jdbc.execute("""
                INSERT INTO products (id, name, description, category_id, unit, selling_price, quantity, is_active)
                VALUES (1, 'Chair', 'Original', 1, 'piece', 100, 5, true), (2, 'Other chair', NULL, 1, 'piece', 200, 2, true)
                """);
        jdbc.execute("ALTER TABLE products ALTER COLUMN id RESTART WITH 3");
        jdbc.execute("""
                CREATE TABLE product_images (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id BIGINT NOT NULL REFERENCES products(id), image_url TEXT NOT NULL, is_primary BOOLEAN, display_order INT)
                """);
        String migration = new ClassPathResource("product_audit.sql").getContentAsString(StandardCharsets.UTF_8);
        // shortcut: H2 has no RLS; the PostgreSQL harness checks the complete migration and policy.
        migration = migration.replace("ALTER TABLE public.product_audit_logs ENABLE ROW LEVEL SECURITY;", "");
        new ResourceDatabasePopulator(new ByteArrayResource(migration.getBytes(StandardCharsets.UTF_8))).execute(database);
        audit = new ProductAuditRepository(jdbc, new ObjectMapper());
        products = new AdminProductService(new AdminProductRepository(jdbc), new AdminCategoryRepository(jdbc), mock(FileStorageService.class), audit);
        transaction = new TransactionTemplate(new DataSourceTransactionManager(database));
    }

    @AfterEach
    void shutdown() { database.shutdown(); }

    private int count() { return jdbc.queryForObject("SELECT COUNT(*) FROM product_audit_logs", Integer.class); }

    @Test
    void recordsOnlyRealChangesWithBeforeAfterActorAndTimestamp() {
        transaction.execute(status -> products.updateProductContent(1L, Map.of("name", "Updated", "description", "New description"), 2L));
        var entries = audit.findByProductId(1L, null);
        assertEquals(Set.of("name", "description"), entries.stream().map(row -> row.fieldName()).collect(Collectors.toSet()));
        var name = entries.stream().filter(row -> row.fieldName().equals("name")).findFirst().orElseThrow();
        assertEquals("\"Chair\"", name.oldValue());
        assertEquals("\"Updated\"", name.newValue());
        assertTrue(entries.stream().allMatch(row -> row.actorUserId().equals(2L) && row.actorUsername().equals("content") && row.changedAt() != null));
        assertTrue(audit.findByProductId(2L, null).isEmpty());
    }

    @Test
    void unchangedFieldsAndEquivalentPricesProduceNoAuditRows() {
        transaction.execute(status -> products.updateProductContent(1L, Map.of("name", " Chair ", "description", "Original"), 2L));
        transaction.execute(status -> products.updateProduct(1L, new SaveProductRequest("Chair", 1L, "piece", new BigDecimal("100.0"), 5, "Original", null, true), 1L));
        assertEquals(0, count());
    }

    @Test
    void creationAndAdminPriceStockStatusChangesAreRecorded() {
        var created = transaction.execute(status -> products.createProduct(new SaveProductRequest("New chair", 1L, "piece", BigDecimal.TEN, 0, null, null, false), 1L));
        assertTrue(audit.findByProductId(created.id(), null).stream().anyMatch(row -> row.fieldName().equals("name") && row.oldValue() == null));
        transaction.execute(status -> products.updateProduct(1L, new SaveProductRequest("Chair", 1L, "piece", new BigDecimal("250"), 9, "Original", null, true), 1L));
        transaction.execute(status -> products.toggleProductStatus(1L, 1L));
        assertEquals(Set.of("selling_price", "quantity", "is_active"), audit.findByProductId(1L, null).stream().map(row -> row.fieldName()).collect(Collectors.toSet()));
    }

    @Test
    void auditFailureRollsBackProductAndAlreadyInsertedLogRows() {
        jdbc.execute("ALTER TABLE product_audit_logs ADD CONSTRAINT audit_failure CHECK (field_name <> 'description')");
        assertThrows(DataAccessException.class, () -> transaction.execute(status -> products.updateProductContent(1L, Map.of("name", "Must rollback", "description", "Must rollback too"), 2L)));
        assertEquals("Chair", products.getProductDetail(1L).name());
        assertEquals("Original", products.getProductDetail(1L).description());
        assertEquals(0, count());
    }

    @Test
    void missingOrInvalidActorCannotLeaveAnUnauditedChange() {
        assertThrows(IllegalArgumentException.class, () -> transaction.execute(status -> products.updateProductContent(1L, Map.of("name", "Forbidden"), null)));
        assertThrows(DataAccessException.class, () -> transaction.execute(status -> products.updateProductContent(1L, Map.of("name", "Forbidden"), 999L)));
        assertEquals("Chair", products.getProductDetail(1L).name());
        assertEquals(0, count());
        assertThrows(IllegalStateException.class, () -> audit.snapshot(1L));
    }

    @Test
    void galleryChangesAreRecordedAndAnotherProductsImageIsRejected() {
        var first = transaction.execute(status -> products.addDirectImageUrl(1L, "https://example.test/one.jpg", 2L));
        var second = transaction.execute(status -> products.addDirectImageUrl(1L, "https://example.test/two.jpg", 2L));
        long secondId = second.stream().filter(image -> image.imageUrl().endsWith("two.jpg")).findFirst().orElseThrow().id();
        transaction.executeWithoutResult(status -> products.setPrimaryImage(1L, secondId, 2L));
        assertEquals("https://example.test/two.jpg", products.getProductDetail(1L).imageUrl());
        transaction.executeWithoutResult(status -> products.deleteProductImage(1L, secondId, 2L));
        assertEquals(first.get(0).imageUrl(), products.getProductDetail(1L).imageUrl());
        assertTrue(audit.findByProductId(1L, null).stream().anyMatch(row -> row.fieldName().equals("images") && row.newValue().contains("two.jpg")));
        jdbc.execute("INSERT INTO product_images (id, product_id, image_url, is_primary, display_order) VALUES (90, 2, 'other.jpg', true, 0)");
        int before = count();
        assertThrows(IllegalArgumentException.class, () -> transaction.executeWithoutResult(status -> products.setPrimaryImage(1L, 90L, 2L)));
        assertEquals(first.get(0).imageUrl(), products.getProductDetail(1L).imageUrl());
        assertEquals(before, count());
    }

    @Test
    void cursorPaginationDoesNotDuplicateOrMixProducts() {
        for (int index = 0; index < 53; index++) jdbc.update("INSERT INTO product_audit_logs (product_id, actor_user_id, field_name, new_value) VALUES (1, 1, 'name', ?)", "\"Value " + index + "\"");
        var first = products.getProductAuditLog(1L, null);
        var second = products.getProductAuditLog(1L, first.getLast().id());
        assertEquals(50, first.size());
        assertEquals(3, second.size());
        assertTrue(first.stream().allMatch(row -> row.id() > second.getFirst().id()));
        assertTrue(products.getProductAuditLog(2L, null).isEmpty());
        assertThrows(IllegalArgumentException.class, () -> products.getProductAuditLog(1L, 0L));
    }
}
