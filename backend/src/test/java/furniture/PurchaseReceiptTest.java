package furniture;

import static org.junit.jupiter.api.Assertions.*;

import java.math.BigDecimal;
import java.util.Arrays;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.transaction.support.TransactionTemplate;

import com.fasterxml.jackson.databind.ObjectMapper;
import furniture.model.admin.supplier.CreateReceiptRequest;
import furniture.model.admin.supplier.CreateReceiptRequest.ReceiptItemRequest;
import furniture.repository.AdminSupplierRepository;
import furniture.service.AdminSupplierService;

class PurchaseReceiptTest {
    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private AdminSupplierService service;
    private TransactionTemplate transaction;

    @BeforeEach
    void setup() {
        database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .setName("receipt_" + java.util.UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE").build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("CREATE TABLE suppliers (id BIGINT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE staff (id BIGINT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE products (id BIGINT PRIMARY KEY, name VARCHAR(200), unit VARCHAR(50), quantity INT NOT NULL)");
        jdbc.execute("""
                CREATE TABLE purchase_receipts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                supplier_id BIGINT NOT NULL REFERENCES suppliers(id), staff_id BIGINT NOT NULL REFERENCES staff(id),
                receipt_date TIMESTAMP, status VARCHAR(30), total_amount NUMERIC(15,2))
                """);
        jdbc.execute("""
                CREATE TABLE purchase_receipt_items (purchase_receipt_id BIGINT REFERENCES purchase_receipts(id),
                product_id BIGINT REFERENCES products(id), quantity INT CHECK (quantity > 0),
                unit_price NUMERIC(15,2) CHECK (unit_price >= 0), amount NUMERIC(15,2),
                PRIMARY KEY (purchase_receipt_id, product_id))
                """);
        jdbc.execute("INSERT INTO suppliers VALUES (1), (2)");
        jdbc.execute("INSERT INTO staff VALUES (1)");
        jdbc.execute("INSERT INTO products VALUES (1, 'Sofa', 'cai', 0), (2, 'Chair', 'cai', 0)");
        service = new AdminSupplierService(new AdminSupplierRepository(jdbc));
        transaction = new TransactionTemplate(new DataSourceTransactionManager(database));
    }

    @AfterEach
    void cleanup() {
        database.shutdown();
    }

    private Long create(String status) {
        return transaction.execute(tx -> service.createReceipt(1L, new CreateReceiptRequest(1L, status,
                List.of(new ReceiptItemRequest(1L, 5, new BigDecimal("3000000"))))));
    }

    private void update(Long supplierId, Long id, String status) {
        transaction.executeWithoutResult(tx -> service.updateReceiptStatus(supplierId, id, status));
    }

    private int stock() {
        return jdbc.queryForObject("SELECT quantity FROM products WHERE id = 1", Integer.class);
    }

    @Test
    void pendingThenCompleteAddsStockExactlyOnceAndLocksReceipt() {
        Long id = create("PENDING");
        assertEquals(0, stock());
        assertEquals(0, new BigDecimal("15000000").compareTo(jdbc.queryForObject(
                "SELECT total_amount FROM purchase_receipts WHERE id = ?", BigDecimal.class, id)));
        assertEquals(5, service.getReceiptItems(1L, id).get(0).quantity());
        update(1L, id, "COMPLETED");
        update(1L, id, "COMPLETED");
        assertEquals(5, stock());
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, "PENDING"));
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, "CANCELLED"));
        assertEquals(5, stock());
    }

    @Test
    void completedOnCreationAddsStockOnce() {
        Long id = create("COMPLETED");
        update(1L, id, "COMPLETED");
        assertEquals(5, stock());
    }

    @Test
    void cancelledReceiptCannotBeReopenedAndDoesNotAddStock() {
        Long id = create("PENDING");
        update(1L, id, "CANCELLED");
        update(1L, id, "CANCELLED");
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, "COMPLETED"));
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, "PENDING"));
        assertEquals(0, stock());
    }

    @Test
    void wrongSupplierMissingReceiptAndInvalidStatusAreRejected() {
        Long id = create("PENDING");
        assertThrows(IllegalArgumentException.class, () -> update(2L, id, "COMPLETED"));
        assertThrows(IllegalArgumentException.class, () -> service.getReceiptItems(2L, id));
        assertThrows(IllegalArgumentException.class, () -> update(1L, 999L, "COMPLETED"));
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, null));
        assertThrows(IllegalArgumentException.class, () -> update(1L, id, "INVALID"));
        assertEquals(0, stock());
    }

    @Test
    void invalidItemsAreRejectedWithoutSavingAnything() {
        for (ReceiptItemRequest item : Arrays.asList(null,
                new ReceiptItemRequest(null, 1, BigDecimal.ONE),
                new ReceiptItemRequest(999L, 1, BigDecimal.ONE),
                new ReceiptItemRequest(1L, null, BigDecimal.ONE),
                new ReceiptItemRequest(1L, 0, BigDecimal.ONE),
                new ReceiptItemRequest(1L, -1, BigDecimal.ONE),
                new ReceiptItemRequest(1L, 1, null),
                new ReceiptItemRequest(1L, 1, BigDecimal.ONE.negate()))) {
            assertThrows(IllegalArgumentException.class, () -> transaction.execute(tx -> service.createReceipt(1L,
                    new CreateReceiptRequest(1L, "COMPLETED", Arrays.asList(item)))));
        }
        var item = new ReceiptItemRequest(1L, 1, BigDecimal.ZERO);
        assertThrows(IllegalArgumentException.class, () -> service.createReceipt(1L,
                new CreateReceiptRequest(1L, "COMPLETED", List.of(item, item))));
        assertThrows(IllegalArgumentException.class, () -> service.createReceipt(1L,
                new CreateReceiptRequest(999L, "COMPLETED", List.of(item))));
        assertThrows(IllegalArgumentException.class, () -> service.createReceipt(1L,
                new CreateReceiptRequest(1L, "UNKNOWN", List.of(item))));
        assertThrows(IllegalArgumentException.class, () -> service.createReceipt(1L,
                new CreateReceiptRequest(1L, "PENDING", List.of())));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM purchase_receipts", Integer.class));
        assertEquals(0, stock());
    }

    @Test
    void fractionalQuantityIsRejectedBeforeItCanBeTruncated() throws Exception {
        var mapper = new ObjectMapper();
        assertThrows(com.fasterxml.jackson.core.JsonProcessingException.class, () -> mapper.readValue(
                "{\"items\":[{\"productId\":1,\"quantity\":1.5,\"unitPrice\":0}]}", CreateReceiptRequest.class));
        assertEquals(5, mapper.readValue(
                "{\"items\":[{\"productId\":1,\"quantity\":5,\"unitPrice\":0}]}", CreateReceiptRequest.class)
                .items().get(0).quantity());
    }

    @Test
    void stockAndStatusRollBackTogetherWhenUpdateFails() {
        Long id = create("PENDING");
        jdbc.execute("ALTER TABLE products ADD CHECK (quantity < 5)");
        assertThrows(org.springframework.dao.DataAccessException.class, () -> update(1L, id, "COMPLETED"));
        assertEquals("PENDING", jdbc.queryForObject("SELECT status FROM purchase_receipts WHERE id = ?", String.class, id));
        assertEquals(0, stock());
    }

    @Test
    void concurrentApprovalsOnlyAddStockOnce() throws Exception {
        Long id = create("PENDING");
        var ready = new CountDownLatch(2);
        var start = new CountDownLatch(1);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var tasks = new java.util.ArrayList<java.util.concurrent.Future<?>>();
            for (int i = 0; i < 2; i++) {
                tasks.add(executor.submit(() -> {
                    ready.countDown();
                    assertTrue(start.await(5, TimeUnit.SECONDS));
                    update(1L, id, "COMPLETED");
                    return null;
                }));
            }
            assertTrue(ready.await(5, TimeUnit.SECONDS));
            start.countDown();
            for (var task : tasks) task.get(10, TimeUnit.SECONDS);
        }
        assertEquals(5, stock());
    }
}
