    @Test
    void deletionWaitsForCheckoutAndArchivesTheVoucherInsteadOfDeletingItsHistory() throws Exception {
        jdbc.execute("ALTER TABLE orders ADD FOREIGN KEY (voucher_id) REFERENCES vouchers(id)");
        var repository = new furniture.repository.AdminPromotionRepository(jdbc);
        var service = new furniture.service.AdminPromotionService(repository, mock(furniture.repository.AdminProductRepository.class), new VoucherService(new VoucherRepository(jdbc)));
        var used = new CountDownLatch(1);
        var release = new CountDownLatch(1);
        var deleting = new CountDownLatch(1);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var buyer = executor.submit(() -> transaction.execute(tx -> {
                var order = orders.createOrder(new CreateOrderRequest(1L, 1L, "Customer", "0901234567", "Street", null,
                        "District", "City", BigDecimal.ZERO, 1L, BigDecimal.ZERO, List.of(item(1, 1))));
                used.countDown();
                try { assertTrue(release.await(5, TimeUnit.SECONDS)); }
                catch (InterruptedException ex) { Thread.currentThread().interrupt(); throw new IllegalStateException(ex); }
                return order;
            }));
            try {
                assertTrue(used.await(5, TimeUnit.SECONDS));
                var deletion = executor.submit(() -> {
                    deleting.countDown();
                    return transaction.execute(tx -> service.deleteVoucher(1L));
                });
                assertTrue(deleting.await(5, TimeUnit.SECONDS));
                release.countDown();
                var order = buyer.get(15, TimeUnit.SECONDS);
                assertEquals(Boolean.TRUE, deletion.get(15, TimeUnit.SECONDS));
                assertTrue(repository.findVoucherById(1L).archived());
                assertEquals(order.totalAmount(), jdbc.queryForObject("SELECT total_amount FROM orders WHERE id = ?", BigDecimal.class, order.orderId()));
                assertEquals(1, service.getVoucherOrders(1L).size());
            } finally { release.countDown(); }
        }
    }

