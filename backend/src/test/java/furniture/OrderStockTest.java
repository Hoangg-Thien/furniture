    @Test
    void voucherLifecyclePreservesCancelledOrderHistoryAndReplacesAtomically() {
        jdbc.execute("ALTER TABLE promotion_programs ADD COLUMN description VARCHAR(100)");
        jdbc.execute("ALTER TABLE vouchers ALTER COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100)");
        var repository = new furniture.repository.AdminPromotionRepository(jdbc);
        var service = new furniture.service.AdminPromotionService(repository, mock(furniture.repository.AdminProductRepository.class), new VoucherService(new VoucherRepository(jdbc)));
        var edit = new furniture.model.admin.promotion.CreateVoucherRequest("EDIT25", new BigDecimal("25"), BigDecimal.ZERO, null, 10, null, null, "ACTIVE", "ORDER", null);
        transaction.execute(tx -> service.updateVoucher(1L, edit));
        assertEquals("EDIT25", repository.findVoucherById(1L).code());
        assertEquals(0, new BigDecimal("25").compareTo(repository.findVoucherById(1L).discountPercent()));
        var order = buy(item(1, 2));
        assertTrue(cancel(order.orderId()));
        assertEquals(0, repository.findVoucherById(1L).usedQuantity());
        assertEquals(1, repository.findVoucherById(1L).ordersCount());
        assertThrows(IllegalStateException.class, () -> transaction.execute(tx -> service.updateVoucher(1L, edit)));
        assertThrows(IllegalArgumentException.class, () -> transaction.execute(tx -> service.replaceVoucher(1L, edit)));
        assertEquals("ACTIVE", repository.findVoucherById(1L).status());
        var replacementRequest = new furniture.model.admin.promotion.CreateVoucherRequest("NEW20", new BigDecimal("20"), BigDecimal.ZERO, null, 100, null, null, "ACTIVE", "ORDER", null);
        var replacement = transaction.execute(tx -> service.replaceVoucher(1L, replacementRequest));
        assertEquals("INACTIVE", repository.findVoucherById(1L).status());
        assertEquals(0, new BigDecimal("25").compareTo(repository.findVoucherById(1L).discountPercent()));
        assertEquals("ACTIVE", replacement.status());
        assertEquals(0, replacement.usedQuantity());
        assertThrows(IllegalArgumentException.class, () -> orders.previewOrder(new CreateOrderRequest(null, null, "Receiver", "0901234567", "Street", null, "District", "City", BigDecimal.ONE, 1L, BigDecimal.ZERO, List.of(item(1, 2)))));
        transaction.executeWithoutResult(tx -> service.deleteVoucher(1L));
        assertTrue(repository.findVoucherById(1L).archived());
        assertEquals(order.totalAmount(), jdbc.queryForObject("SELECT total_amount FROM orders WHERE id = ?", BigDecimal.class, order.orderId()));
        assertEquals(1, service.getVoucherOrders(1L).size());
        assertThrows(IllegalStateException.class, () -> transaction.executeWithoutResult(tx -> service.updateVoucherStatus(1L, "ACTIVE")));
        transaction.executeWithoutResult(tx -> service.deleteVoucher(replacement.id()));
        assertTrue(repository.findVoucherById(replacement.id()).archived());
        assertTrue(new VoucherRepository(jdbc).findVoucherWithProgramByCode("NEW20").isEmpty());
        assertEquals(0, new VoucherRepository(jdbc).approveVoucher(replacement.id()));
    }

