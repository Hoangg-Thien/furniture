package furniture;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.mockStatic;

import java.math.BigDecimal;
import java.nio.file.Files;
import java.util.Arrays;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.transaction.support.TransactionTemplate;

import furniture.model.CreateOrderRequest;
import furniture.model.OrderItemDto;
import furniture.model.OrderResponse;
import furniture.model.admin.order.CancelOrderRequest;
import furniture.repository.AdminOrderRepository;
import furniture.repository.OrderRepository;
import furniture.service.AdminInvoiceService;
import furniture.service.AdminOrderService;
import furniture.service.OrderService;

class OrderStockTest {
    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private OrderService orders;
    private AdminOrderService admin;
    private TransactionTemplate transaction;

    @BeforeEach
    void setup() {
        database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .setName("stock_" + java.util.UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE").build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, username VARCHAR(50))");
        jdbc.execute("CREATE TABLE staff (id BIGINT PRIMARY KEY, user_id BIGINT, full_name VARCHAR(200))");
        jdbc.execute("CREATE TABLE customers (id BIGINT PRIMARY KEY, user_id BIGINT, full_name VARCHAR(200), phone VARCHAR(20), address TEXT)");
        jdbc.execute("CREATE TABLE products (id BIGINT PRIMARY KEY, name VARCHAR(200), image_url TEXT, unit VARCHAR(50), quantity INT NOT NULL CHECK (quantity >= 0), is_active BOOLEAN)");
        jdbc.execute("CREATE TABLE vouchers (id BIGINT PRIMARY KEY, code VARCHAR(50), quantity INT, used_quantity INT)");
        jdbc.execute("""
                CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id BIGINT REFERENCES customers(id), staff_id BIGINT, order_date TIMESTAMP, status VARCHAR(30),
                total_amount NUMERIC(15,2), voucher_id BIGINT, discount_amount NUMERIC(15,2), shipping_address TEXT)
                """);
        jdbc.execute("""
                CREATE TABLE order_items (order_id BIGINT REFERENCES orders(id), product_id BIGINT REFERENCES products(id),
                quantity INT CHECK (quantity > 0), unit_price NUMERIC(15,2) CHECK (unit_price >= 0), amount NUMERIC(15,2),
                PRIMARY KEY (order_id, product_id))
                """);
        var migration = new ResourceDatabasePopulator(new ClassPathResource("order_stock.sql"));
        migration.execute(database);
        migration.execute(database);
        jdbc.execute("INSERT INTO customers VALUES (1, 1, 'Customer', '0901234567', 'Old address')");
        jdbc.execute("INSERT INTO products VALUES (1, 'Sofa', NULL, 'cai', 10, TRUE), (2, 'Chair', NULL, 'cai', 1, TRUE)");
        jdbc.execute("INSERT INTO vouchers VALUES (1, 'TEST', 10, 0)");
        orders = new OrderService(new OrderRepository(jdbc));
        admin = new AdminOrderService(new AdminOrderRepository(jdbc), mock(AdminInvoiceService.class));
        transaction = new TransactionTemplate(new DataSourceTransactionManager(database));
    }

    @AfterEach
    void cleanup() {
        database.shutdown();
    }

    private OrderItemDto item(long id, int quantity) {
        return new OrderItemDto(id, quantity, BigDecimal.TEN);
    }

    private OrderResponse buy(OrderItemDto... items) {
        // Checkout hiện ghi file seed; chặn mọi thao tác file trong test để giữ nguyên dữ liệu dự án.
        try (var files = mockStatic(Files.class)) {
            return transaction.execute(tx -> orders.createOrder(new CreateOrderRequest(
                    1L, 1L, "Customer", "0901234567", "New address", null, null, null,
                    BigDecimal.TEN, 1L, BigDecimal.ZERO, Arrays.asList(items))));
        }
    }

    private int stock(long id) {
        return jdbc.queryForObject("SELECT quantity FROM products WHERE id = ?", Integer.class, id);
    }

    private boolean cancel(long id) {
        return transaction.execute(tx -> orders.cancelOrder(id));
    }

    @Test
    void checkoutDeductsStockAndCustomerCancellationRestoresItOnlyOnce() {
        Long id = buy(item(1, 3)).orderId();
        assertEquals(7, stock(1));
        assertEquals(1, jdbc.queryForObject("SELECT used_quantity FROM vouchers WHERE id = 1", Integer.class));
        assertTrue(cancel(id));
        assertFalse(cancel(id));
        assertEquals(10, stock(1));
        assertEquals(0, jdbc.queryForObject("SELECT used_quantity FROM vouchers WHERE id = 1", Integer.class));
        assertThrows(IllegalStateException.class, () -> transaction.executeWithoutResult(tx ->
                admin.cancelOrder(id, new CancelOrderRequest("Customer changed mind"))));
        assertEquals(10, stock(1));
    }

    @Test
    void adminCancellationAlsoRestoresStockOnlyOnce() {
        Long id = buy(item(1, 3)).orderId();
        transaction.executeWithoutResult(tx -> admin.cancelOrder(id, new CancelOrderRequest("Customer changed mind")));
        assertFalse(cancel(id));
        assertEquals(10, stock(1));
    }

    @Test
    void legacyOrdersDoNotIncreaseStockWhenCancelledByCustomerOrAdmin() {
        jdbc.update("INSERT INTO orders (id, customer_id, status, total_amount, discount_amount) VALUES (101, 1, 'PENDING', 10, 0), (102, 1, 'PENDING', 10, 0)");
        jdbc.update("INSERT INTO order_items VALUES (101, 1, 3, 10, 30), (102, 1, 3, 10, 30)");
        assertTrue(cancel(101L));
        transaction.executeWithoutResult(tx -> admin.cancelOrder(102L, new CancelOrderRequest("Legacy order")));
        assertEquals(10, stock(1));
    }

    @Test
    void insufficientStockRollsBackEarlierDeductionsAndDoesNotCreateOrder() {
        assertThrows(IllegalArgumentException.class, () -> buy(item(1, 3), item(2, 2)));
        assertEquals(10, stock(1));
        assertEquals(1, stock(2));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM orders", Integer.class));
        assertEquals("Old address", jdbc.queryForObject("SELECT address FROM customers WHERE id = 1", String.class));
    }

    @Test
    void invalidDuplicateMissingInactiveAndSoldOutProductsAreRejected() {
        for (var items : List.of(Arrays.asList((OrderItemDto) null), List.of(item(1, 0)),
                List.of(item(1, -1)), List.of(item(999, 1)), List.of(item(1, 1), item(1, 2)))) {
            assertThrows(IllegalArgumentException.class, () -> buy(items.toArray(OrderItemDto[]::new)));
        }
        jdbc.update("UPDATE products SET is_active = FALSE WHERE id = 1");
        assertThrows(IllegalArgumentException.class, () -> buy(item(1, 1)));
        jdbc.update("UPDATE products SET quantity = 0 WHERE id = 2");
        assertThrows(IllegalArgumentException.class, () -> buy(item(2, 1)));
        assertEquals(10, stock(1));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM orders", Integer.class));
    }

    @Test
    void failedItemInsertRollsBackOrderStockAndVoucher() {
        jdbc.execute("ALTER TABLE order_items ADD CHECK (quantity < 3)");
        assertThrows(org.springframework.dao.DataAccessException.class, () -> buy(item(1, 3)));
        assertEquals(10, stock(1));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM orders", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT used_quantity FROM vouchers WHERE id = 1", Integer.class));
    }

    @Test
    void concurrentBuyersCannotBuyTheSameLastItem() throws Exception {
        var ready = new CountDownLatch(2);
        var start = new CountDownLatch(1);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var tasks = new java.util.ArrayList<java.util.concurrent.Future<Boolean>>();
            for (int i = 0; i < 2; i++) {
                tasks.add(executor.submit(() -> {
                    ready.countDown();
                    assertTrue(start.await(5, TimeUnit.SECONDS));
                    try {
                        buy(item(2, 1));
                        return true;
                    } catch (IllegalArgumentException insufficientStock) {
                        return false;
                    }
                }));
            }
            assertTrue(ready.await(5, TimeUnit.SECONDS));
            start.countDown();
            int successes = 0;
            for (var task : tasks) if (task.get(15, TimeUnit.SECONDS)) successes++;
            assertEquals(1, successes);
        }
        assertEquals(0, stock(2));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM orders", Integer.class));
    }
}
