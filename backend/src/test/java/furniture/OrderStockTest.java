        assertThrows(IllegalStateException.class, () -> transaction.executeWithoutResult(tx -> service.updateVoucherStatus(1L, "ACTIVE")));
        transaction.executeWithoutResult(tx -> service.deleteVoucher(replacement.id()));
        assertEquals(null, repository.findVoucherById(replacement.id()));
        assertTrue(new VoucherRepository(jdbc).findVoucherWithProgramByCode("NEW20").isEmpty());
