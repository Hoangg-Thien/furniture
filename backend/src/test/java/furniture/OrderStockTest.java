    @BeforeEach
    void setup() {
        database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .setName("stock_" + java.util.UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE").build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, username VARCHAR(50))");
        jdbc.execute("CREATE TABLE staff (id BIGINT PRIMARY KEY, user_id BIGINT, full_name VARCHAR(200))");
        jdbc.execute("CREATE TABLE customers (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, user_id BIGINT NOT NULL, full_name VARCHAR(200), phone VARCHAR(20), address TEXT)");
        jdbc.execute("CREATE TABLE products (id BIGINT PRIMARY KEY, name VARCHAR(200), image_url TEXT, unit VARCHAR(50), quantity INT NOT NULL CHECK (quantity >= 0), is_active BOOLEAN, selling_price NUMERIC(15,2) DEFAULT 10)");
        jdbc.execute("CREATE TABLE promotion_programs (id BIGINT PRIMARY KEY, name VARCHAR(100), status VARCHAR(20), start_date TIMESTAMP, end_date TIMESTAMP)");
        jdbc.execute("CREATE TABLE product_discounts (promotion_program_id BIGINT, product_id BIGINT, discount_percent NUMERIC, start_date TIMESTAMP, end_date TIMESTAMP)");
        jdbc.execute("CREATE TABLE order_discounts (promotion_program_id BIGINT, minimum_amount NUMERIC, discount_percent NUMERIC, start_date TIMESTAMP, end_date TIMESTAMP)");
        jdbc.execute("""
                CREATE TABLE vouchers (id BIGINT PRIMARY KEY, code VARCHAR(50), quantity INT, used_quantity INT,
                promotion_program_id BIGINT DEFAULT 1, discount_percent NUMERIC DEFAULT 10, minimum_amount NUMERIC DEFAULT 0,
                maximum_discount NUMERIC, status VARCHAR(20) DEFAULT 'ACTIVE',
                start_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP - INTERVAL '1' DAY,
                end_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP + INTERVAL '1' DAY)
                """);
        jdbc.execute("""
                CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id BIGINT REFERENCES customers(id), staff_id BIGINT, order_date TIMESTAMP, status VARCHAR(30),
                total_amount NUMERIC(15,2), voucher_id BIGINT, discount_amount NUMERIC(15,2), shipping_address TEXT)
                """);
        jdbc.execute("""
                CREATE TABLE order_items (order_id BIGINT REFERENCES orders(id), product_id BIGINT REFERENCES products(id),
                quantity INT CHECK (quantity > 0), unit_price NUMERIC(15,2) CHECK (unit_price >= 0), amount NUMERIC(15,2),
                PRIMARY KEY (order_id, product_id))
                """);
        var migration = new ResourceDatabasePopulator(new ClassPathResource("order_stock.sql"));
        migration.execute(database);
        migration.execute(database);
        var guests = new ResourceDatabasePopulator(new ClassPathResource("guest_checkout.sql"));
        guests.execute(database);
        guests.execute(database);
        jdbc.execute("INSERT INTO customers VALUES (1, 1, 'Customer', '0901234567', 'Old address')");
        jdbc.execute("INSERT INTO products (id, name, image_url, unit, quantity, is_active) VALUES (1, 'Sofa', NULL, 'cai', 10, TRUE), (2, 'Chair', NULL, 'cai', 1, TRUE)");
        jdbc.execute("INSERT INTO promotion_programs VALUES (1, 'Test program', 'ACTIVE', CURRENT_TIMESTAMP - INTERVAL '1' DAY, CURRENT_TIMESTAMP + INTERVAL '1' DAY)");
        jdbc.execute("INSERT INTO vouchers (id, code, quantity, used_quantity) VALUES (1, 'TEST', 10, 0)");
        orders = new OrderService(new OrderRepository(jdbc), new VoucherService(new VoucherRepository(jdbc)));
        admin = new AdminOrderService(new AdminOrderRepository(jdbc), mock(AdminInvoiceService.class));
        transaction = new TransactionTemplate(new DataSourceTransactionManager(database));
    }

